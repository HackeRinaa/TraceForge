/**
 * Prepares the local demo: creates (or reuses) a demo user, a "Demo Workspace" project flagged as demo data, and an API
 * key, then writes the key to .env.demo for the demo services. Idempotent. Development only.
 *
 * Usage: pnpm demo:setup
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import {
  baseSchema,
  clickhouseSchema,
  loadConfig,
  loadDotEnv,
  postgresSchema,
} from '@traceforge/config';
import { newApiKey, sha256Hex } from '@traceforge/domain';
import {
  createPg,
  createProject,
  createWorkspace,
  findActiveKeyByHash,
  insertApiKey,
  listProjects,
  listWorkspacesForUser,
  schema,
} from '@traceforge/storage';
import { eq } from 'drizzle-orm';
import { z } from 'zod';

loadDotEnv();
const cfg = loadConfig(
  z.object({ ...baseSchema.shape, ...postgresSchema.shape, ...clickhouseSchema.shape }),
);
if (cfg.NODE_ENV === 'production')
  throw new Error('demo:setup must not run with NODE_ENV=production');

const API_URL = process.env.API_URL ?? 'http://localhost:4000';
const WEB_URL = process.env.WEB_URL ?? 'http://localhost:3000';
const EMAIL = process.env.DEMO_USER_EMAIL ?? 'demo@traceforge.local';
// Development-only default. Override with DEMO_USER_PASSWORD; never used when NODE_ENV=production.
const PASSWORD = process.env.DEMO_USER_PASSWORD ?? 'traceforge-demo-1';
const ENV_FILE = '.env.demo';
const PROJECT_NAME = 'Demo Workspace API';

async function api(path: string, body: unknown): Promise<Response> {
  return fetch(`${API_URL}${path}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', origin: WEB_URL.replace(/\/$/, '') },
    body: JSON.stringify(body),
  });
}

// 1. User: register through the real API, or confirm credentials if the account already exists.
let res = await api('/v1/auth/register', { email: EMAIL, name: 'Demo User', password: PASSWORD });
if (res.status === 409) res = await api('/v1/auth/login', { email: EMAIL, password: PASSWORD });
if (!res.ok) {
  throw new Error(
    `could not register or sign in the demo user (HTTP ${res.status}): ${await res.text()}`,
  );
}

const pg = createPg(cfg.DATABASE_URL, { max: 2 });
try {
  const [user] = await pg.db
    .select()
    .from(schema.users)
    .where(eq(schema.users.email, EMAIL.toLowerCase()));
  if (!user) throw new Error('demo user not found after registration');

  // 2. Workspace + project flagged as demo data (the UI labels demo projects).
  let [workspace] = await listWorkspacesForUser(pg.db, user.id);
  workspace ??= await createWorkspace(pg.db, { name: 'Demo Workspace', ownerId: user.id });
  const projects = await listProjects(pg.db, workspace.id);
  let project = projects.find((p) => p.isDemo);
  project ??= await createProject(pg.db, {
    workspaceId: workspace.id,
    name: PROJECT_NAME,
    isDemo: true,
  });

  // 3. API key: reuse the one in .env.demo if it is still valid, otherwise mint a new one.
  let existing = '';
  if (existsSync(ENV_FILE)) {
    existing = /^TRACEFORGE_API_KEY=(.+)$/m.exec(readFileSync(ENV_FILE, 'utf8'))?.[1]?.trim() ?? '';
  }
  const valid = existing ? await findActiveKeyByHash(pg.db, sha256Hex(existing)) : null;
  let secret = existing;
  if (!valid || valid.projectId !== project.id) {
    const key = newApiKey();
    await insertApiKey(pg.db, {
      projectId: project.id,
      name: 'demo-services',
      prefix: key.prefix,
      keyHash: key.hash,
      createdBy: user.id,
    });
    secret = key.secret;
  }

  writeFileSync(
    ENV_FILE,
    [
      '# Generated by `pnpm demo:setup`. Contains a secret; do not commit.',
      `TRACEFORGE_API_KEY=${secret}`,
      `TRACEFORGE_OTLP_ENDPOINT=${API_URL}/v1/traces`,
      `DEMO_PROJECT_ID=${project.id}`,
      '',
    ].join('\n'),
  );

  console.log('Demo ready.');
  console.log(
    `  Sign in:   ${WEB_URL}/login  (${EMAIL}; password from DEMO_USER_PASSWORD or the documented dev default)`,
  );
  console.log(`  Project:   ${WEB_URL}/projects/${project.id}/overview`);
  console.log(`  API key written to ${ENV_FILE}`);
} finally {
  await pg.close();
}
